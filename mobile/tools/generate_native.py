"""Generate the skin tables for the native apps from tools/skins.json (itself extracted from the web CSS).

    python3 mobile/tools/extract_skins.py && python3 mobile/tools/generate_native.py
"""
import json, pathlib

HERE = pathlib.Path(__file__).parent
D = json.loads((HERE / 'skins.json').read_text())
KEYS = [('bg','bg'),('panel','panel'),('inset','inset'),('line','line'),('text','text'),('text-dim','textDim'),
        ('amber','amber'),('amber-dim','amberDim'),('on-amber','onAmber'),('glow','glow'),('glow-green','glowGreen'),
        ('green','green'),('js','js'),('css-lang','cssLang'),('danger','danger')]
UNLOCK_NONE = None

def hexs(v): return v.lstrip('#').upper()

# ---------------------------------------------------------------- Swift
def swift():
    o = ['// GENERATED by mobile/tools/generate_native.py from the web skins (src/styles/skins/*.css). Do not edit by hand.',
         'import SwiftUI', '',
         'enum SkinData {',
         f'    static let defaultSkin = "{D["default"]}"',
         '    static let autoByTod: [String: String] = [' + ', '.join(f'"{k}": "{v}"' for k, v in D['autoByTod'].items()) + ']',
         '', '    static let all: [Skin] = [']
    for s in D['skins']:
        o.append('        Skin(')
        o.append(f'            id: "{s["id"]}", group: .{s["group"]}, label: "{s["label"]}", note: "{s["note"]}",')
        o.append('            modes: [' + ', '.join('.' + m for m in s['modes']) + f'], rk: {s["rk"]},')
        if s['unlock']:
            u = s['unlock']; o.append(f'            unlock: Unlock(game: "{u["game"]}", min: {u["min"]}, hint: "{u["hint"]}"),')
        else:
            o.append('            unlock: nil,')
        o.append('            palettes: [')
        for mode, p in s['palettes'].items():
            args = ', '.join(f'{sw}: 0x{hexs(p[css])}' for css, sw in KEYS)
            o.append(f'                .{mode}: Palette({args}),')
        o.append('            ]),')
    o.append('    ]')
    o.append('}')
    return '\n'.join(o) + '\n'

# ---------------------------------------------------------------- Kotlin
def kotlin():
    o = ['// GENERATED by mobile/tools/generate_native.py from the web skins (src/styles/skins/*.css). Do not edit by hand.',
         'package dev.zune.portfolio.theme', '',
         'object SkinData {',
         f'    const val DEFAULT_SKIN = "{D["default"]}"',
         '    val autoByTod: Map<String, String> = mapOf(' + ', '.join(f'"{k}" to "{v}"' for k, v in D['autoByTod'].items()) + ')',
         '', '    val all: List<Skin> = listOf(']
    for s in D['skins']:
        o.append('        Skin(')
        o.append(f'            id = "{s["id"]}", group = SkinGroup.{s["group"].upper()}, label = "{s["label"]}", note = "{s["note"]}",')
        o.append('            modes = listOf(' + ', '.join('Mode.' + m.upper() for m in s['modes']) + f'), rk = {s["rk"]}f,')
        if s['unlock']:
            u = s['unlock']; o.append(f'            unlock = Unlock(game = "{u["game"]}", min = {u["min"]}, hint = "{u["hint"]}"),')
        else:
            o.append('            unlock = null,')
        o.append('            palettes = mapOf(')
        for mode, p in s['palettes'].items():
            args = ', '.join(f'{sw} = 0xFF{hexs(p[css])}' for css, sw in KEYS)
            o.append(f'                Mode.{mode.upper()} to Palette({args}),')
        o.append('            )),')
    o.append('    )')
    o.append('}')
    return '\n'.join(o) + '\n'

root = HERE.parent
ios = root / 'ios/ZunePortfolio/Theme'; ios.mkdir(parents=True, exist_ok=True)
(ios / 'SkinData.swift').write_text(swift())
kt = root / 'android/app/src/main/java/dev/zune/portfolio/theme'; kt.mkdir(parents=True, exist_ok=True)
(kt / 'SkinData.kt').write_text(kotlin())
print('wrote', ios / 'SkinData.swift'); print('wrote', kt / 'SkinData.kt')
